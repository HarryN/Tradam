export function translate(locale: Locale, key: string): string {
  if (!key) return '';
  
  // 1. Exact match check
  const dict = translations[locale];
  if (dict[key]) return dict[key];

  // 2. Case-insensitive and trimmed match check (Robust for dynamic data)
  const normalizedKey = key.toLowerCase().trim();
  const match = Object.keys(dict).find(k => k.toLowerCase().trim() === normalizedKey);
  
  if (match) {
    return dict[match];
  }

  // 3. Fallback to English dictionary (case-insensitive)
  if (locale !== 'en') {
    const enDict = translations.en;
    const enMatch = Object.keys(enDict).find(k => k.toLowerCase().trim() === normalizedKey);
    if (enMatch && dict[enMatch]) return dict[enMatch];
  }

  // 4. Return original key if no match found
  return key;
}
